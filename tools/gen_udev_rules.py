#!/usr/bin/env python3
"""Generate udev rules from Android ueventd.rc files.

Android HALs in the LXC container run with numeric Android IDs (AIDs), and most
Android user/group names do not exist in the Ubuntu Touch user database, so the
rules use numeric IDs. Only plain /dev/<node> entries are translated: udev's
KERNEL key matches the kernel device name, so entries for sub-directories
(e.g. /dev/dri/*, /dev/input/*) cannot be expressed this way and are skipped
(Ubuntu Touch ships its own rules for input devices).
"""
import sys

AID = {
    'root': 0, 'system': 1000, 'radio': 1001, 'bluetooth': 1002, 'graphics': 1003,
    'input': 1004, 'audio': 1005, 'camera': 1006, 'log': 1007, 'compass': 1008,
    'mount': 1009, 'wifi': 1010, 'adb': 1011, 'install': 1012, 'media': 1013,
    'dhcp': 1014, 'sdcard_rw': 1015, 'vpn': 1016, 'keystore': 1017, 'usb': 1018,
    'drm': 1019, 'mdnsr': 1020, 'gps': 1021, 'media_rw': 1023, 'mtp': 1024,
    'drmrpc': 1026, 'nfc': 1027, 'sdcard_r': 1028, 'clat': 1029,
    'loop_radio': 1030, 'media_drm': 1031, 'package_info': 1032, 'logd': 1036,
    'shared_relro': 1037, 'audioserver': 1041, 'mediacodec': 1046,
    'cameraserver': 1047, 'firewall': 1048, 'nvram': 1050, 'dns': 1051,
    'secure_element': 1068, 'lmkd': 1069, 'gpu_service': 1072,
    'network_stack': 1073, 'shell': 2000, 'cache': 2001, 'diag': 2002,
    'net_bt_admin': 3001, 'net_bt': 3002, 'inet': 3003, 'net_raw': 3004,
    'net_admin': 3005, 'net_bw_stats': 3006, 'net_bw_acct': 3007,
    'readproc': 3009, 'wakelock': 3010, 'uhid': 3011, 'everybody': 9997,
    'misc': 9998, 'nobody': 9999,
}


def aid(name):
    if name in AID:
        return str(AID[name])
    if name.startswith('oem_') and name[4:].isdigit():  # OEM reserved range
        return name[4:]
    if name.isdigit():
        return name
    raise KeyError(name)


def main(out, *sources):
    rules, skipped, unknown, seen = [], 0, set(), set()
    for src in sources:
        for line in open(src, encoding='utf-8', errors='replace'):
            f = line.split()
            if len(f) < 4 or not f[0].startswith('/dev/'):
                continue
            node, mode, owner, group = f[0][len('/dev/'):], f[1], f[2], f[3]
            if '/' in node:
                skipped += 1
                continue
            try:
                uid, gid = aid(owner), aid(group)
            except KeyError as e:
                unknown.add(str(e))
                continue
            rule = f'ACTION=="add", KERNEL=="{node}", OWNER="{uid}", GROUP="{gid}", MODE="{mode}"'
            if node in seen:  # later files (vendor) override earlier ones
                rules = [r for r in rules if f'KERNEL=="{node}",' not in r]
            seen.add(node)
            rules.append(rule)
    with open(out, 'w') as fh:
        fh.write('# Generated by gen_udev_rules.py from: ' + ' '.join(sources) + '\n')
        fh.write('# Numeric Android AIDs; see the script for details.\n')
        fh.write('\n'.join(rules) + '\n')
    print(f'{len(rules)} rules, {skipped} sub-directory entries skipped, unknown names: {sorted(unknown) or "none"}')


if __name__ == '__main__':
    main(sys.argv[1], *sys.argv[2:])
